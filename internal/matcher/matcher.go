package matcher

import (
	"fmt"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/smford/tf-move-gen/internal/tfplan"
)

// DefaultMinConfidence is the default minimum similarity threshold.
const DefaultMinConfidence = 0.70

// Config defines options for matching.
type Config struct {
	MinConfidence float64
}

// Match represents a matched delete-create pair with similarity details.
type Match struct {
	From              string
	To                string
	Confidence        float64
	MatchedAttributes []string
	Source            *tfplan.ResourceChange
	Target            *tfplan.ResourceChange
}

// Result contains all matched pairs and any remaining unmatched resources.
type Result struct {
	Matches          []Match
	UnmatchedDeletes []*tfplan.ResourceChange
	UnmatchedCreates []*tfplan.ResourceChange
}

// transientAttrs are infrastructure metadata attributes generated by providers.
var transientAttrs = map[string]bool{
	"id":           true,
	"arn":          true,
	"etag":         true,
	"unique_id":    true,
	"create_date":  true,
	"created_date": true,
	"time_created": true,
	"generation":   true,
	"self_link":    true,
	"version_id":   true,
	"deposed_key":  true,
}

// FindMatches groups candidate resources and executes greedy bipartite matching.
func FindMatches(plan *tfplan.Plan, cfg Config) (*Result, error) {
	if cfg.MinConfidence <= 0 {
		cfg.MinConfidence = DefaultMinConfidence
	}

	deletes, creates := plan.Candidates()

	// Group candidates by (Type, ProviderBaseName)
	type groupKey struct {
		resourceType string
		provider     string
	}

	deletesByGroup := make(map[groupKey][]*tfplan.ResourceChange)
	for _, d := range deletes {
		key := groupKey{
			resourceType: d.Type,
			provider:     tfplan.ProviderBaseName(d.ProviderName),
		}
		deletesByGroup[key] = append(deletesByGroup[key], d)
	}

	createsByGroup := make(map[groupKey][]*tfplan.ResourceChange)
	for _, c := range creates {
		key := groupKey{
			resourceType: c.Type,
			provider:     tfplan.ProviderBaseName(c.ProviderName),
		}
		createsByGroup[key] = append(createsByGroup[key], c)
	}

	// Collect all groups
	allGroups := make(map[groupKey]bool)
	for k := range deletesByGroup {
		allGroups[k] = true
	}
	for k := range createsByGroup {
		allGroups[k] = true
	}

	var allMatches []Match
	var unmatchedDeletes []*tfplan.ResourceChange
	var unmatchedCreates []*tfplan.ResourceChange

	// Process each group deterministically
	var groupKeys []groupKey
	for k := range allGroups {
		groupKeys = append(groupKeys, k)
	}
	sort.Slice(groupKeys, func(i, j int) bool {
		if groupKeys[i].resourceType != groupKeys[j].resourceType {
			return groupKeys[i].resourceType < groupKeys[j].resourceType
		}
		return groupKeys[i].provider < groupKeys[j].provider
	})

	for _, g := range groupKeys {
		delGroup := deletesByGroup[g]
		createGroup := createsByGroup[g]

		matches, uDel, uCreate := matchGroup(delGroup, createGroup, cfg.MinConfidence)
		allMatches = append(allMatches, matches...)
		unmatchedDeletes = append(unmatchedDeletes, uDel...)
		unmatchedCreates = append(unmatchedCreates, uCreate...)
	}

	// Sort matches by From address for consistent output
	sort.Slice(allMatches, func(i, j int) bool {
		return allMatches[i].From < allMatches[j].From
	})

	// Sort unmatched deletes and creates by address
	sort.Slice(unmatchedDeletes, func(i, j int) bool {
		return unmatchedDeletes[i].Address < unmatchedDeletes[j].Address
	})
	sort.Slice(unmatchedCreates, func(i, j int) bool {
		return unmatchedCreates[i].Address < unmatchedCreates[j].Address
	})

	return &Result{
		Matches:          allMatches,
		UnmatchedDeletes: unmatchedDeletes,
		UnmatchedCreates: unmatchedCreates,
	}, nil
}

type pairScore struct {
	delIdx            int
	createIdx         int
	score             float64
	matchedAttributes []string
}

// matchGroup executes greedy bipartite matching for candidates of the same type and provider.
func matchGroup(deletes []*tfplan.ResourceChange, creates []*tfplan.ResourceChange, minConfidence float64) ([]Match, []*tfplan.ResourceChange, []*tfplan.ResourceChange) {
	if len(deletes) == 0 {
		return nil, nil, creates
	}
	if len(creates) == 0 {
		return nil, deletes, nil
	}

	var pairs []pairScore
	for i, d := range deletes {
		for j, c := range creates {
			score, matchedAttrs := ComputeSimilarity(d, c)
			if score >= minConfidence {
				pairs = append(pairs, pairScore{
					delIdx:            i,
					createIdx:         j,
					score:             score,
					matchedAttributes: matchedAttrs,
				})
			}
		}
	}

	// Sort pairs descending by score, breaking ties by addresses for determinism
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].score != pairs[j].score {
			return pairs[i].score > pairs[j].score
		}
		if deletes[pairs[i].delIdx].Address != deletes[pairs[j].delIdx].Address {
			return deletes[pairs[i].delIdx].Address < deletes[pairs[j].delIdx].Address
		}
		return creates[pairs[i].createIdx].Address < creates[pairs[j].createIdx].Address
	})

	matchedDeletes := make(map[int]bool)
	matchedCreates := make(map[int]bool)
	var matches []Match

	for _, p := range pairs {
		if matchedDeletes[p.delIdx] || matchedCreates[p.createIdx] {
			continue
		}
		matchedDeletes[p.delIdx] = true
		matchedCreates[p.createIdx] = true

		d := deletes[p.delIdx]
		c := creates[p.createIdx]

		matches = append(matches, Match{
			From:              d.Address,
			To:                c.Address,
			Confidence:        p.score,
			MatchedAttributes: p.matchedAttributes,
			Source:            d,
			Target:            c,
		})
	}

	var uDel []*tfplan.ResourceChange
	for i, d := range deletes {
		if !matchedDeletes[i] {
			uDel = append(uDel, d)
		}
	}

	var uCreate []*tfplan.ResourceChange
	for j, c := range creates {
		if !matchedCreates[j] {
			uCreate = append(uCreate, c)
		}
	}

	return matches, uDel, uCreate
}

// ComputeSimilarity calculates attribute similarity score (0.0 to 1.0) and lists matched attributes.
func ComputeSimilarity(del *tfplan.ResourceChange, create *tfplan.ResourceChange) (float64, []string) {
	beforeFlat := make(map[string]any)
	if del.Change.Before != nil {
		flatten("", del.Change.Before, beforeFlat)
	}

	afterFlat := make(map[string]any)
	if create.Change.After != nil {
		flatten("", create.Change.After, afterFlat)
	}

	unknownPaths := make(map[string]bool)
	if create.Change.AfterUnknown != nil {
		flattenUnknown("", create.Change.AfterUnknown, unknownPaths)
	}

	// Collect all unique candidate paths from before and after
	allPathsMap := make(map[string]bool)
	for k := range beforeFlat {
		allPathsMap[k] = true
	}
	for k := range afterFlat {
		allPathsMap[k] = true
	}

	var totalWeight float64
	var matchedWeight float64
	topLevelMatched := make(map[string]bool)

	for path := range allPathsMap {
		valBefore, hasBefore := beforeFlat[path]
		valAfter, hasAfter := afterFlat[path]

		// Ignore if unknown in after
		if isPathUnknown(path, unknownPaths) {
			continue
		}

		// Ignore transient provider attributes if absent or null in after
		if isTransient(path) && (!hasAfter || valAfter == nil) {
			continue
		}

		// If neither side has a non-nil value, skip
		if (!hasBefore || valBefore == nil) && (!hasAfter || valAfter == nil) {
			continue
		}

		weight := attributeWeight(path)
		totalWeight += weight

		score := compareValues(valBefore, valAfter)
		matchedWeight += weight * score

		if score >= 0.999 {
			topLevel := topLevelAttr(path)
			topLevelMatched[topLevel] = true
		}
	}

	if totalWeight == 0 {
		// If both before and after had zero comparable attributes but identical type/provider
		return 1.0, nil
	}

	confidence := matchedWeight / totalWeight
	if confidence > 1.0 {
		confidence = 1.0
	}

	var matchedAttrs []string
	for k := range topLevelMatched {
		matchedAttrs = append(matchedAttrs, k)
	}
	sort.Strings(matchedAttrs)

	return confidence, matchedAttrs
}

func isPathUnknown(path string, unknownPaths map[string]bool) bool {
	if unknownPaths[path] {
		return true
	}
	// Check if any ancestor path is unknown (e.g. "tags_all" makes "tags_all.Name" unknown)
	parts := strings.Split(path, ".")
	for i := 1; i <= len(parts); i++ {
		prefix := strings.Join(parts[:i], ".")
		if unknownPaths[prefix] {
			return true
		}
	}
	return false
}

func isTransient(path string) bool {
	base := topLevelAttr(path)
	if transientAttrs[base] {
		return true
	}
	// Also check last segment
	parts := strings.Split(path, ".")
	last := parts[len(parts)-1]
	// strip bracket index if any
	if idx := strings.Index(last, "["); idx != -1 {
		last = last[:idx]
	}
	return transientAttrs[last]
}

func attributeWeight(path string) float64 {
	// High-signal attributes get 2.0x weight
	switch path {
	case "name", "bucket", "identifier", "cidr_block", "function_name", "role", "tags.Name":
		return 2.0
	}
	if strings.HasSuffix(path, ".name") || strings.HasSuffix(path, ".identifier") || strings.HasSuffix(path, ".cidr_block") || strings.HasSuffix(path, ".bucket") || strings.HasSuffix(path, ".function_name") || strings.HasSuffix(path, ".role") {
		return 2.0
	}
	return 1.0
}

func topLevelAttr(path string) string {
	idx := strings.Index(path, ".")
	bracket := strings.Index(path, "[")
	if idx == -1 && bracket == -1 {
		return path
	}
	if idx != -1 && bracket != -1 {
		if idx < bracket {
			return path[:idx]
		}
		return path[:bracket]
	}
	if idx != -1 {
		return path[:idx]
	}
	return path[:bracket]
}

func flatten(prefix string, val any, out map[string]any) {
	if val == nil {
		if prefix != "" {
			out[prefix] = nil
		}
		return
	}

	switch v := val.(type) {
	case map[string]any:
		for k, item := range v {
			p := k
			if prefix != "" {
				p = prefix + "." + k
			}
			flatten(p, item, out)
		}
	case []any:
		// If slice of maps, flatten by index
		isSliceOfMaps := len(v) > 0
		for _, elem := range v {
			if _, ok := elem.(map[string]any); !ok {
				isSliceOfMaps = false
				break
			}
		}
		if isSliceOfMaps {
			for i, elem := range v {
				p := prefix + "[" + strconv.Itoa(i) + "]"
				flatten(p, elem, out)
			}
		} else {
			if prefix != "" {
				out[prefix] = v
			}
		}
	default:
		if prefix != "" {
			out[prefix] = v
		}
	}
}

func flattenUnknown(prefix string, val any, out map[string]bool) {
	if val == nil {
		return
	}
	switch v := val.(type) {
	case bool:
		if v && prefix != "" {
			out[prefix] = true
		}
	case map[string]any:
		if prefix != "" {
			out[prefix] = true
		}
		for k, item := range v {
			p := k
			if prefix != "" {
				p = prefix + "." + k
			}
			flattenUnknown(p, item, out)
		}
	case []any:
		if prefix != "" {
			out[prefix] = true
		}
		for i, item := range v {
			p := prefix + "[" + strconv.Itoa(i) + "]"
			flattenUnknown(p, item, out)
		}
	}
}

func compareValues(v1, v2 any) float64 {
	if v1 == nil && v2 == nil {
		return 1.0
	}
	if v1 == nil || v2 == nil {
		return 0.0
	}

	// Compare slices using set Jaccard similarity if applicable
	s1, isSlice1 := toSlice(v1)
	s2, isSlice2 := toSlice(v2)
	if isSlice1 && isSlice2 {
		return sliceJaccard(s1, s2)
	}

	// Direct equality or string equality
	if reflect.DeepEqual(v1, v2) {
		return 1.0
	}

	// Compare formatted strings
	str1 := fmt.Sprintf("%v", v1)
	str2 := fmt.Sprintf("%v", v2)
	if str1 == str2 {
		return 1.0
	}

	return 0.0
}

func toSlice(v any) ([]any, bool) {
	if v == nil {
		return nil, false
	}
	val := reflect.ValueOf(v)
	if val.Kind() == reflect.Slice {
		var res []any
		for i := 0; i < val.Len(); i++ {
			res = append(res, val.Index(i).Interface())
		}
		return res, true
	}
	return nil, false
}

func sliceJaccard(s1, s2 []any) float64 {
	if len(s1) == 0 && len(s2) == 0 {
		return 1.0
	}
	set1 := make(map[string]bool)
	for _, item := range s1 {
		set1[fmt.Sprintf("%v", item)] = true
	}
	set2 := make(map[string]bool)
	for _, item := range s2 {
		set2[fmt.Sprintf("%v", item)] = true
	}

	intersection := 0
	for k := range set1 {
		if set2[k] {
			intersection++
		}
	}

	unionMap := make(map[string]bool)
	for k := range set1 {
		unionMap[k] = true
	}
	for k := range set2 {
		unionMap[k] = true
	}

	if len(unionMap) == 0 {
		return 1.0
	}
	return float64(intersection) / float64(len(unionMap))
}
